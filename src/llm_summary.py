"""Phase 8: build llm/stats_summary.md from the result files of phases 2-7 (numbers only, no interpretation).

Also computes forward forecasts from the LAST observed day (needed for the simulated recommendations prompt),
with the same models and train-only parameters as phases 3-5, saved to results/08_forward_forecasts.csv.
"""
from __future__ import annotations

from datetime import date

import numpy as np
import pandas as pd

from . import arima, data, garch, multivariate as mv
from .config import ROOT, load_config, path


def _fmt(x, nd=4):
    if isinstance(x, (bool, np.bool_)):
        return "yes" if x else "no"
    if isinstance(x, (int, np.integer)):
        return str(int(x))
    if isinstance(x, (float, np.floating)):
        if np.isnan(x):
            return "—"
        if x != 0 and (abs(x) < 1e-3 or abs(x) >= 1e5):
            return f"{x:.3e}"
        return f"{x:.{nd}f}"
    return str(x)


def _table(df: pd.DataFrame, nd=4) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(_fmt(r[c], nd) for c in cols) + " |")
    return "\n".join(lines)


def forward_forecasts(H: int = 10) -> pd.DataFrame:
    """Forecasts for the H trading days AFTER the last observation, parameters estimated on train only."""
    panel = data.load_panel()
    train, _ = data.chrono_split(panel)
    te, last = train.index[-1], panel.index[-1]
    future = pd.bdate_range(last + pd.Timedelta(days=1), periods=H)      # business days (holidays not removed)
    ly = panel["CONVERTS_log_price"]
    out = []
    # Random walk = ARIMA(0,1,0) without drift, train parameters, conditioned on all data up to the last day.
    rw = arima.fit_arima(ly.loc[:te], (0, 1, 0)).apply(ly.to_numpy()).get_forecast(H)
    m, ci = rw.predicted_mean, rw.conf_int(alpha=0.05)
    for h in range(H):
        out.append({"model": "rw (ARIMA(0,1,0))", "series": "CONVERTS", "origin": last.date(), "h": h + 1, "target date (business day)": future[h].date(),
                    "level forecast": np.exp(m[h]), "lower 95%": np.exp(ci[h, 0]), "upper 95%": np.exp(ci[h, 1])})
    # VECM CONVERTS-NVDA fitted on train, forecast from the full history.
    lv = panel[["CONVERTS_log_price", "NVDA_log_price"]].set_axis(["CONVERTS", "NVDA"], axis=1)
    v = mv.fit_vecm(lv.loc[:te], 1, 1)
    f = mv.vecm_level_forecasts(v, pd.concat([lv, pd.DataFrame(np.nan, index=future, columns=lv.columns)]).ffill(),
                                "CONVERTS", [last], H, "vecm_nvda")
    for h, r in f.iterrows():
        out.append({"model": "vecm_nvda", "series": "CONVERTS", "origin": last.date(), "h": int(r["horizon"]),
                    "target date (business day)": future[int(r["horizon"]) - 1].date(), "level forecast": r["y_pred"],
                    "lower 95%": r["lower"], "upper 95%": r["upper"]})
    # GARCH(1,1)-t volatility of CONVERTS, PURE, BTC: annualised volatility forecast.
    for s in ("CONVERTS", "PURE", "BTC"):
        r100 = 100 * panel[f"{s}_log_return"].dropna()
        res = garch.fit(r100, "GARCH(1,1)-t", last_obs=r100.index[r100.index.get_loc(te) + 1])
        var = res.forecast(horizon=H, start=last, reindex=False).variance.iloc[0].to_numpy()
        for h in range(H):
            out.append({"model": "garch_t (volatility)", "series": s, "origin": last.date(), "h": h + 1,
                        "target date (business day)": future[h].date(), "forecast annualised vol": np.sqrt(var[h] * 252) / 100})
    df = pd.DataFrame(out)
    df.to_csv(path("results") / "08_forward_forecasts.csv", index=False)
    return df


def build(out_file=None) -> str:
    """Write llm/stats_summary.md. Every number is read from results/ (or computed by forward_forecasts)."""
    cfg = load_config()
    R = path("results")
    rd = lambda f, **k: pd.read_csv(R / f, **k)
    panel = data.load_panel()
    s = []
    s.append("# Project statistical summary (generated by code, numbers only)\n")
    s.append(f"*Generated on {date.today()} by `llm/make_stats_summary.py` from the files in `results/`. No interpretation.*\n")
    s.append("## 0. Data\n")
    s.append(_table(pd.DataFrame([
        {"item": "source", "value": "Yahoo Finance (yfinance 1.8.0), adjusted prices (Adj Close), daily frequency"},
        {"item": "period", "value": f"{panel.index[0].date()} → {panel.index[-1].date()} ({len(panel)} US trading days)"},
        {"item": "series", "value": "CONVERTS = equal-weighted mean of the log returns of IREN, CIFR, WULF; PURE = same for MARA, CLSK, RIOT; BTC = BTC-USD; NVDA"},
        {"item": "train / test", "value": f"{cfg['split']['n_train']} / {cfg['split']['n_test']} days ({cfg['split']['train_start']} → {cfg['split']['train_end']} / {cfg['split']['test_start']} → {cfg['split']['test_end']})"},
        {"item": "pivot date (detected by structural-break tests)", "value": cfg["pivot_date"]},
    ])))

    # ---------------------------------------------------------------- section A: descriptive + stationarity
    s.append("\n## A. Descriptive statistics and stationarity (for prompt a)\n")
    d = rd("02_descriptive_stats.csv", index_col=0)
    d.index.name = "series"
    d = d.reset_index()
    d["variance"] = d["std"] ** 2
    s.append("### A.1 Daily log returns\n")
    s.append(_table(d[["series", "n", "mean", "variance", "std", "annualised vol", "skewness", "excess kurtosis", "min", "date min", "max", "date max"]], 5))
    st = rd("02_stationarity_adf_kpss.csv")
    s.append("\n### A.2 ADF (H0: unit root) and KPSS (H0: stationarity) tests\n")
    s.append("*KPSS p-values are bounded to [0.01, 0.10] by the interpolation table.*\n")
    s.append(_table(st[["series", "form", "regression", "adf_stat", "adf_p", "kpss_stat", "kpss_p", "verdict"]]))
    lb = rd("02_ljungbox_returns.csv")
    s.append("\n### A.3 Ljung-Box on returns and squared returns (p-values)\n")
    s.append(_table(lb.pivot_table(index=["series", "variable"], columns="lag", values="p_value", sort=False).reset_index().rename(columns=lambda c: f"lag {c}" if isinstance(c, (int, np.integer)) else c)))
    stl = rd("02_stl_seasonality.csv")
    s.append("\n### A.4 STL decomposition of the log price (seasonal strength F_S, trend strength F_T)\n")
    s.append(_table(stl[["series", "period", "seasonal_strength_FS", "trend_strength_FT", "var_share_seasonal"]]))

    # ---------------------------------------------------------------- section B: model results
    s.append("\n## B. Model results (for prompt b)\n")
    g = rd("03_order_grid_converts.csv")
    s.append("### B.1 ARIMA on the CONVERTS log level (train) — 5 best by AIC\n")
    s.append(_table(g.sort_values("AIC").head(5)[["order", "drift", "k", "loglik", "AIC", "BIC"]]))
    au = rd("03_auto_arima.csv")
    s.append("\n*Automatic search (pmdarima):*\n")
    s.append(_table(au))
    dg = rd("03_residual_diagnostics.csv")
    s.append("\n*Chosen model: ARIMA(0,1,0) without drift. Residual diagnostics:*\n")
    s.append(_table(dg[dg["model"] == "ARIMA(0,1,0)"][["series", "test", "parameter", "statistic", "p_value", "conclusion (5%)"]]))
    ls = rd("04_var_lag_selection.csv")
    s.append("\n### B.2 VAR on returns [BTC, NVDA, CONVERTS, PURE]\n")
    s.append("*Order chosen by information criterion (p = 0..10), best p per period:*\n")
    best = ls.groupby("period").apply(lambda x: pd.Series({c: int(x.loc[x[c].idxmin(), "p"]) for c in ["AIC", "BIC", "HQIC", "FPE"]}), include_groups=False).reset_index()
    s.append(_table(best))
    s.append("\n*VAR(1) estimated in each period. Granger causality (F test), p-values:*\n")
    gr = rd("04_granger.csv")
    s.append(_table(gr.pivot_table(index=["cause", "effect"], columns="period", values="p_value", sort=False).reset_index()))
    irf = rd("04_irf.csv")
    s.append("\n*Orthogonalised impulse responses (order BTC, NVDA, CONVERTS, PURE), same-day effect (h = 0), 95% band:*\n")
    s.append(_table(irf[irf["h"] == 0][["period", "shock", "response", "irf", "lower", "upper"]]))
    co = rd("04_cointegration.csv")
    s.append("\n### B.3 Cointegration (log prices): Johansen (unrestricted constant) and Engle-Granger\n")
    s.append(_table(co[["pair", "period", "n", "trace_r0", "cv95_trace_r0", "maxeig_r0", "cv95_maxeig_r0", "rank_trace", "rank_maxeig", "EG_p"]]))
    s.append("\n*R check (urca): same trace statistics; 5% critical value for r = 0 is 17.95 in urca (15.49 in statsmodels).*\n")
    ve = rd("04_vecm.csv")
    s.append("\n*VECM where the trace test (statsmodels) finds rank 1:*\n")
    s.append(_table(ve))
    al = rd("05_archlm.csv")
    s.append("\n### B.4 Volatility: ARCH-LM and GARCH\n")
    s.append(_table(al[["residuals of", "sample", "lag", "LM", "p_value"]]))
    gc = rd("05_garch_comparison.csv")
    s.append("\n*Comparison of variance models (train, returns in %):*\n")
    s.append(_table(gc[["series", "model", "loglik", "AIC", "BIC", "persistence", "half-life (d)", "LR vs constant variance", "p(LR)"]]))
    pp = rd("05_persistence_pre_post.csv")
    s.append("\n*GARCH(1,1)-t before / after the pivot:*\n")
    s.append(_table(pp))
    ab = rd("05_absret_corr_pre_post.csv")
    s.append("\n*Correlation of absolute returns before / after the pivot:*\n")
    s.append(_table(ab))
    s.append("\n### B.5 Dynamic correlation\n")
    dc = rd("07_dcc_params.csv")
    s.append(_table(dc))
    rc = rd("07_rolling_corr_90.csv", index_col=0, parse_dates=True)
    piv = pd.Timestamp(cfg["pivot_date"])
    cross = rc["CONVERTS–NVDA"] > rc["CONVERTS–BTC"]
    crossp = rc["PURE–NVDA"] > rc["PURE–BTC"]
    s.append("\n*90-day rolling correlation — share of days where the correlation with NVDA exceeds the one with BTC:*\n")
    s.append(_table(pd.DataFrame({"period": ["pre-pivot", "post-pivot"],
                                  "CONVERTS": [cross[rc.index < piv].mean(), cross[rc.index >= piv].mean()],
                                  "PURE": [crossp[rc.index < piv].mean(), crossp[rc.index >= piv].mean()]})))

    # ---------------------------------------------------------------- section C: forecasts
    s.append("\n## C. Forecasts and evaluation (for prompts b and c)\n")
    s.append("*Protocol: parameters estimated on train, rolling origins over the 123 test days, CONVERTS index level.*\n")
    mc = rd("model_comparison.csv")
    s.append(_table(mc[["model", "family", "h", "n", "MSE", "RMSE", "MAE", "MAPE_%", "95% PI coverage", "RMSE / RMSE rw", "interpretability", "training time (s)"]], 3))
    dm = rd("07_dm_tests.csv")
    s.append("\n*Diebold-Mariano test (HLN correction, loss = squared error; DM > 0 = model 1 less accurate):*\n")
    s.append(_table(dm[["model 1", "model 2", "h", "n", "mean_d", "DM", "p_value", "p NW(20)"]]))
    dv = rd("07_dm_vol.csv")
    s.append("\n*Volatility forecasts, GARCH(1,1)-t vs constant variance (QLIKE loss):*\n")
    s.append(_table(dv[["series", "h", "mean_d", "DM", "p_value", "DM NW(20)", "p NW(20)"]]))
    ff = forward_forecasts()
    s.append(f"\n### C.2 Out-of-sample forecasts (origin: last observed day, {panel.index[-1].date()})\n")
    s.append(f"*Last observed CONVERTS level: {_fmt(float(panel['CONVERTS_level'].iloc[-1]), 2)} (base 100 on {panel.index[0].date()}).*\n")
    lvl = ff[ff["model"] != "garch_t (volatility)"][["model", "h", "target date (business day)", "level forecast", "lower 95%", "upper 95%"]]
    s.append(_table(lvl[lvl["h"].isin([1, 5, 10])], 2))
    vol = ff[ff["model"] == "garch_t (volatility)"][["series", "h", "forecast annualised vol"]]
    s.append("\n")
    s.append(_table(vol[vol["h"].isin([1, 5, 10])], 3))
    s.append("\n*Transaction costs, liquidity and position sizing: not modelled in this project.*\n")
    text = "\n".join(s) + "\n"
    out = out_file or (ROOT / "llm" / "stats_summary.md")
    out.parent.mkdir(exist_ok=True)
    out.write_text(text, encoding="utf-8")
    return str(out)
